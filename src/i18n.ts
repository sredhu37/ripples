const dicts: Record<Lang, Dict> = { en, de, pl };

export type UiKey = keyof typeof en;

export function t(lang: Lang, key: UiKey, vars: Record<string, string | number> = {}): string {
  const raw = dicts[lang]?.[key] ?? en[key];
  return raw.replace(/\{(\w+)\}/g, (_m, k: string) => String(vars[k] ?? ""));
}

export const SPEECH_LANG: Record<Lang, string> = {
  en: "en-IN",
  de: "de-DE",
  pl: "pl-PL",
};

export const CURRENCY_SYMBOL: Record<Lang, string> = {
  en: "₹",
  de: "€",
  pl: "zł",
};

export const LOCALE_CODE: Record<Lang, string> = {
  en: "en-IN",
  de: "de-DE",
  pl: "pl-PL",
};

export function formatNumber(n: number, lang: Lang): string {
  return new Intl.NumberFormat(LOCALE_CODE[lang]).format(n);
}

export function formatDate(date: Date, lang: Lang): string {
  return new Intl.DateTimeFormat(LOCALE_CODE[lang], { dateStyle: "medium" }).format(date);
}
